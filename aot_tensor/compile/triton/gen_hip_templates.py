"""Generate checked-in HIP templates from the CUDA sources. Not used at runtime."""

import argparse
import difflib
import logging
import re
import sys
import tempfile
from pathlib import Path

from torch.utils.hipify import (  # @manual=//caffe2/torch/utils/hipify:hipify_python-library
    hipify_python,
)

logger: logging.Logger = logging.getLogger(__name__)
TEMPLATE_NAMES: tuple[str, ...] = ("kernel.h", "kernel.cpp")


def _restore_include_names(text: str, renames: dict[str, str]) -> str:
    pattern = (
        r"//(?:\\\r?\n|[^\n])*|/\*.*?\*/"
        r'|R"(?P<delimiter>[^ ()\\\t\r\n]{0,16})\(.*?\)(?P=delimiter)"'
        r'|"(?:\\.|[^"\\\r\n])*"|\'(?:\\.|[^\'\\\r\n])*\''
        r"|(?P<include>^[ \t]*#[ \t]*include[ \t]*)"
        r'(?P<header>"[^"\r\n]+"|<[^>\r\n]+>)'
    )

    def restore(match: re.Match[str]) -> str:
        header = match.group("header")
        if header is None:
            return match.group(0)
        path = header[1:-1]
        return match.group("include") + header[0] + renames.get(path, path) + header[-1]

    return re.sub(pattern, restore, text, flags=re.MULTILINE | re.DOTALL)


def hipify_sources(source_dir: Path) -> dict[str, str]:
    """Select only this call's outputs; hipify also retains results from earlier calls."""
    results = hipify_python.hipify(
        project_directory=str(source_dir),
        output_directory=str(source_dir),
        includes=[str(source_dir / name) for name in TEMPLATE_NAMES],
        is_pytorch_extension=True,
        show_progress=False,
    )
    outputs: dict[str, Path] = {}
    for name in TEMPLATE_NAMES:
        result = results[str(source_dir / name)]
        if (
            result.current_state != hipify_python.CurrentState.DONE
            or result.hipified_path is None
        ):
            raise RuntimeError(f"Hipify did not produce {name}")
        outputs[name] = Path(result.hipified_path)
    renames = {path.name: name for name, path in outputs.items()}
    texts = {name: path.read_text(encoding="utf-8") for name, path in outputs.items()}
    for name, text in texts.items():
        text = _restore_include_names(text, renames)
        text = text.removeprefix(hipify_python.HIPIFY_C_BREADCRUMB)
        header = (
            "// @"
            + f"generated by gen_hip_templates.py from ../{name}; edit that file instead.\n"
        )
        texts[name] = header + text
    return texts


def generate(templates_dir: Path) -> dict[str, str]:
    """Return generated text without changing the checkout or importing its resources."""
    with tempfile.TemporaryDirectory(prefix="aott_hipify_") as temporary:
        source = Path(temporary)
        for name in TEMPLATE_NAMES:
            (source / name).write_bytes((templates_dir / name).read_bytes())
        return hipify_sources(source)


def synchronize(templates_dir: Path, *, write: bool = False) -> int:
    generated = generate(templates_dir)
    changed = False
    for name, text in generated.items():
        path = templates_dir / "hip" / name
        original = path.read_bytes().decode("utf-8") if path.exists() else ""
        if original == text:
            continue
        changed = True
        sys.stdout.write(
            "".join(
                difflib.unified_diff(
                    original.splitlines(keepends=True),
                    text.splitlines(keepends=True),
                    fromfile=str(path),
                    tofile=str(path) + " (generated)",
                )
            )
        )
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
    if changed and not write:
        logger.error(
            "Stale HIP templates. Regenerate with --write --templates-dir %s",
            templates_dir,
        )
        return 1
    logger.info("HIP templates are up to date")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument(
        "--check",
        action="store_true",
        help="fail if generated HIP copies are stale (default)",
    )
    modes.add_argument(
        "--write",
        action="store_true",
        help="regenerate HIP copies in the specified source checkout",
    )
    parser.add_argument("--templates-dir", type=Path)
    args = parser.parse_args(argv)
    if args.write and args.templates_dir is None:
        parser.error(
            "--write requires --templates-dir pointing to your source checkout"
        )
    root: Path = args.templates_dir or Path(__file__).with_name("templates")
    if args.templates_dir is None and not root.is_dir():
        parser.error("--templates-dir is required when templates are not packaged")
    return synchronize(root, write=args.write)


def run() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    sys.exit(main())


if __name__ == "__main__":
    run()
