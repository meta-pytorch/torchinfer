import contextlib
import io
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from aot_tensor.compile.triton.gen_hip_templates import (
    _restore_include_names,
    generate,
    main,
)

_HEADER = "#pragma once\n#include <cuda.h>\nstruct Grid { cudaStream_t stream; };\n"
_SOURCE = '#include "kernel.h"\nCUdevice current_device() {\n  CUdevice device;\n  cuCtxGetDevice(&device);\n  return device;\n}\n'


class GenHipTemplatesTest(unittest.TestCase):
    def setUp(self) -> None:
        super().setUp()
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root: Path = Path(temporary.name)
        (self.root / "kernel.h").write_text(_HEADER)
        (self.root / "kernel.cpp").write_text(_SOURCE)

    def test_maps_apis_and_keeps_original_header_name(self) -> None:
        generated = generate(self.root)
        self.assertEqual({"kernel.h", "kernel.cpp"}, set(generated))
        self.assertIn("hipStream_t stream", generated["kernel.h"])
        self.assertIn("hipDevice_t current_device()", generated["kernel.cpp"])
        self.assertIn("hipCtxGetDevice(&device)", generated["kernel.cpp"])
        self.assertIn('#include "kernel.h"', generated["kernel.cpp"])
        self.assertNotIn("kernel_hip.h", generated["kernel.cpp"])
        self.assertNotIn(
            "!!! This is a file automatically generated by hipify",
            generated["kernel.cpp"],
        )
        self.assertTrue(
            generated["kernel.cpp"].startswith(
                "// @" + "generated by gen_hip_templates.py"
            )
        )

    def test_generation_preserves_filename_text_outside_includes(self) -> None:
        extra = (
            'const char* filename = "kernel_hip.h";\n'
            "// kernel_hip.h\n"
            "int kernel_hip_h = kernel_hip.h;\n"
        )
        (self.root / "kernel.cpp").write_bytes((_SOURCE + extra).encode("utf-8"))
        generated = generate(self.root)["kernel.cpp"]
        self.assertIn('#include "kernel.h"', generated)
        self.assertIn(extra, generated)

    def test_restores_only_include_operands(self) -> None:
        text = (
            '#include "kernel_hip.h" // kernel_hip.h\n'
            "\t# include <kernel_hip.h>\n"
            '#include "other/kernel_hip.h"\n'
            '#include "unrelated.h"\n'
            '#define HEADER "kernel_hip.h"\n'
            'const char* filename = "kernel_hip.h";\n'
            "int kernel_hip_h = kernel_hip.h;\n"
        )
        expected = (
            '#include "kernel.h" // kernel_hip.h\n'
            "\t# include <kernel.h>\n"
            '#include "other/kernel_hip.h"\n'
            '#include "unrelated.h"\n'
            '#define HEADER "kernel_hip.h"\n'
            'const char* filename = "kernel_hip.h";\n'
            "int kernel_hip_h = kernel_hip.h;\n"
        )
        self.assertEqual(
            expected, _restore_include_names(text, {"kernel_hip.h": "kernel.h"})
        )

    def test_include_like_text_in_comments_and_literals_is_unchanged(self) -> None:
        cases = [
            "// kernel_hip.h\n",
            '/*\n#include "kernel_hip.h"\n*/\n',
            '// continued \\\n#include "kernel_hip.h"\n',
            'const char* text = "#include \\"kernel_hip.h\\"";\n',
            'const char* text = R"note(\n#include "kernel_hip.h"\n)note";\n',
            'const char* text = u8R"(\n#include "kernel_hip.h"\n)";\n',
            "char letter = 'h'; // kernel_hip.h\n",
        ]
        for text in cases:
            with self.subTest(text=text):
                self.assertEqual(
                    text, _restore_include_names(text, {"kernel_hip.h": "kernel.h"})
                )

    def test_unterminated_quotes_do_not_hide_later_includes(self) -> None:
        cases = [
            ("constexpr auto before = 1'024;\n", "constexpr auto after = 2'048;\n"),
            ('#error message with an unmatched "\n', ""),
            ('#if 0\nprose with an unmatched "\n#endif\n', ""),
        ]
        for prefix, suffix in cases:
            with self.subTest(prefix=prefix):
                self.assertEqual(
                    prefix + '#include "kernel.h"\n' + suffix,
                    _restore_include_names(
                        prefix + '#include "kernel_hip.h"\n' + suffix,
                        {"kernel_hip.h": "kernel.h"},
                    ),
                )

    def test_repeat_calls_have_no_deleted_tempdir_results(self) -> None:
        first = generate(self.root)
        self.assertEqual(first, generate(self.root))
        (self.root / "kernel.cpp").write_text(
            _SOURCE.replace("current_device", "updated_device")
        )
        second = generate(self.root)
        self.assertNotEqual(first["kernel.cpp"], second["kernel.cpp"])
        self.assertIn("updated_device", second["kernel.cpp"])
        self.assertEqual(second, generate(self.root))

    def test_generation_leaves_source_files_unchanged(self) -> None:
        generate(self.root)
        self.assertEqual(_HEADER, (self.root / "kernel.h").read_text())
        self.assertEqual(_SOURCE, (self.root / "kernel.cpp").read_text())
        self.assertFalse((self.root / "hip").exists())

    def test_conditional_backend_logic_is_preserved(self) -> None:
        conditional = "void setup(CUfunction func) {\n#ifdef USE_ROCM\n  (void)func;\n#else\n  cuFuncSetCacheConfig(func, CU_FUNC_CACHE_PREFER_SHARED);\n#endif\n}\n"
        (self.root / "kernel.cpp").write_text(conditional)
        generated = generate(self.root)["kernel.cpp"]
        self.assertIn("void setup(hipFunction_t func)", generated)
        self.assertIn("#ifdef USE_ROCM\n  (void)func;\n#else", generated)
        self.assertIn("hipFuncSetCacheConfig", generated)
        self.assertIn("#endif", generated)

    def test_missing_input_prevents_generation(self) -> None:
        (self.root / "kernel.cpp").unlink()
        with self.assertRaises(FileNotFoundError):
            generate(self.root)
        self.assertFalse((self.root / "hip").exists())

    def test_write_then_check_and_second_write_are_clean(self) -> None:
        args = ["--templates-dir", str(self.root)]
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(0, main(["--write", *args]))
        outputs = {
            name: (self.root / "hip" / name).read_bytes()
            for name in ("kernel.h", "kernel.cpp")
        }
        with contextlib.redirect_stdout(io.StringIO()) as output:
            self.assertEqual(0, main(["--check", *args]))
            self.assertEqual(0, main(["--write", *args]))
        self.assertEqual("", output.getvalue())
        self.assertEqual(
            outputs, {name: (self.root / "hip" / name).read_bytes() for name in outputs}
        )

    def test_check_reports_stale_copy_without_writing(self) -> None:
        args = ["--templates-dir", str(self.root)]
        with contextlib.redirect_stdout(io.StringIO()):
            main(["--write", *args])
        path = self.root / "hip/kernel.cpp"
        original = path.read_bytes()
        (self.root / "kernel.cpp").write_text(
            _SOURCE.replace("return device;", "return device + 1;")
        )
        with (
            contextlib.redirect_stdout(io.StringIO()) as output,
            self.assertLogs(
                "aot_tensor.compile.triton.gen_hip_templates", level="ERROR"
            ),
        ):
            self.assertEqual(1, main(["--check", *args]))
        self.assertIn("+  return device + 1;", output.getvalue())
        self.assertEqual(original, path.read_bytes())

    def test_check_detects_line_ending_drift(self) -> None:
        args = ["--templates-dir", str(self.root)]
        with contextlib.redirect_stdout(io.StringIO()):
            main(["--write", *args])
        path = self.root / "hip/kernel.h"
        original = path.read_bytes().replace(b"\n", b"\r\n")
        path.write_bytes(original)
        with (
            contextlib.redirect_stdout(io.StringIO()),
            self.assertLogs(
                "aot_tensor.compile.triton.gen_hip_templates", level="ERROR"
            ),
        ):
            self.assertEqual(1, main(["--check", *args]))
        self.assertEqual(original, path.read_bytes())

    def test_write_uses_utf8_bytes_independent_of_text_defaults(self) -> None:
        source = _SOURCE + 'const char* label = "caf\u00e9";\n'
        (self.root / "kernel.cpp").write_bytes(source.encode("utf-8"))
        expected = generate(self.root)
        write_text = Path.write_text

        def platform_write_text(
            path: Path,
            text: str,
            encoding: str | None = None,
            errors: str | None = None,
            newline: str | None = None,
        ) -> int:
            return write_text(
                path,
                text,
                encoding=encoding or "cp1252",
                errors=errors,
                newline=newline,
            )

        with patch.object(
            Path, "write_text", autospec=True, side_effect=platform_write_text
        ):
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(
                    0, main(["--write", "--templates-dir", str(self.root)])
                )
            for name, text in expected.items():
                self.assertEqual(
                    text.encode("utf-8"), (self.root / "hip" / name).read_bytes()
                )
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(
                    0, main(["--check", "--templates-dir", str(self.root)])
                )
        self.assertIn(b"caf\xc3\xa9", (self.root / "hip/kernel.cpp").read_bytes())

    def test_reads_hipify_output_as_utf8_with_non_utf8_defaults(self) -> None:
        label = 'const char* label = "caf\u00e9";\n'
        (self.root / "kernel.cpp").write_bytes((_SOURCE + label).encode("utf-8"))
        read_text = Path.read_text

        def platform_read_text(
            path: Path, encoding: str | None = None, errors: str | None = None
        ) -> str:
            return read_text(path, encoding=encoding or "cp1252", errors=errors)

        with patch.object(
            Path, "read_text", autospec=True, side_effect=platform_read_text
        ):
            generated = generate(self.root)
        self.assertIn(label, generated["kernel.cpp"])

    def test_check_without_packaged_templates_requests_directory(self) -> None:
        with (
            patch(
                "aot_tensor.compile.triton.gen_hip_templates.__file__",
                str(self.root / "gen_hip_templates.py"),
            ),
            contextlib.redirect_stderr(io.StringIO()) as error_output,
            self.assertRaises(SystemExit) as error,
        ):
            main(["--check"])
        self.assertEqual(2, error.exception.code)
        self.assertIn("--templates-dir", error_output.getvalue())

    def test_write_requires_explicit_checkout_directory(self) -> None:
        with (
            contextlib.redirect_stderr(io.StringIO()),
            self.assertRaises(SystemExit) as error,
        ):
            main(["--write"])
        self.assertEqual(2, error.exception.code)
